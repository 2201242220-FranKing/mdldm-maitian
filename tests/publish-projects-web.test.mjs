test('authenticated composer saves an ordered image plan, without a video or browser launch', async t => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mt-publish-web-'));
  process.env.MAITIAN_CONFIG = path.join(tmp, 'config.json');
  process.env.MAITIAN_DB = path.join(tmp, 'hub.db');
  const root = path.join(tmp, 'projects'); fs.mkdirSync(root);
  const plugin = path.join(tmp, 'plugin'); fs.mkdirSync(path.join(plugin, 'lib'), { recursive: true });
  fs.writeFileSync(path.join(plugin, 'package.json'), '{"type":"module"}');
  fs.writeFileSync(path.join(plugin, 'manifest.json'), '{"version":"test"}');
  fs.writeFileSync(path.join(plugin, 'lib', 'publish.js'), '');
  fs.writeFileSync(path.join(plugin, 'lib', 'bundle.js'), `
    export const len = s => [...(s || '')].length;
    export const PLATFORMS = { xhs: { name: '小红书', fields: { title: [1,20], body: [1,1000] } } };
    export function validate(b, files) {
      const p = b.platforms.xhs;
      return { errors: [...(!b.video ? ['缺少 video'] : files.has(b.video) ? [] : ['找不到视频']), ...(!p.title || !p.body ? ['文案为空'] : []),
        ...(/https?:/.test(p.body) ? ['正文里有链接'] : [])], warnings: [] };
    }
  `);
  fs.writeFileSync(process.env.MAITIAN_CONFIG, JSON.stringify({ rootPath: root, driver: 'direct', plugin: 'local', pluginDir: plugin, web: { key: 'test-key', port: 0 }, disabled: [] }));
  const { startWeb } = await import('../src/web.mjs');
  await import('../src/followers.mjs');
  const { getEpisode, getTasks, getSnapshot, setTask, db } = await import('../src/db.mjs');
  const server = startWeb(); await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); db.close(); fs.rmSync(tmp, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const auth = { cookie: 'mt_key=test-key' };
  const post = (url, body, extra = {}) => fetch(base + url, { method: 'POST', headers: { ...auth, 'content-type': 'application/json', ...extra }, body: JSON.stringify(body) });
  const create = async () => { const r = await post('/api/publish-drafts', { mediaType: 'images' }); assert.equal(r.status, 201); return (await r.json()).id; };
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aDVkAAAAASUVORK5CYII=', 'base64');
  const upload = (id, name, body = png) => fetch(`${base}/api/publish-drafts/${id}/assets?name=${encodeURIComponent(name)}`, { method: 'POST', headers: { ...auth, 'content-type': 'application/octet-stream' }, body });
  assert.equal((await fetch(base + '/api/publish-drafts', { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' })).status, 401);
  assert.equal((await post('/api/publish-drafts', { mediaType: 'images' }, { origin: 'https://other.example' })).status, 403);
  assert.equal((await post('/api/publish-drafts', { mediaType: 'text' })).status, 400);
  assert.equal((await fetch(base + '/api/publish-drafts', { headers: auth })).status, 405);
  assert.equal((await post('/api/publish-drafts', { mediaType: 'video' }, { 'content-type': 'text/plain' })).status, 415);
  const id = await create();
  assert.equal((await upload(id, '../escape.png')).status, 400);
  assert.equal((await upload(id, 'bad.png', Buffer.from('not an image'))).status, 400);
  assert.equal((await upload(id, 'photo.svg')).status, 400);
  assert.equal((await upload(id, 'empty.png', Buffer.alloc(0))).status, 413);
  assert.equal((await upload('invalid-id', 'photo.png')).status, 400);
  const first = await (await upload(id, 'first.png')).json();
  const second = await (await upload(id, 'second.png')).json();
  const content = { title: '本地测试', body: '这是测试正文', topics: ['主题'], assets: [second.file, first.file] };
  assert.equal((await post(`/api/publish-drafts/${id}/prepare`, { ...content, assets: [first.file, first.file] })).status, 400);
  assert.equal((await post(`/api/publish-drafts/${id}/prepare`, { ...content, assets: ['../outside.png'] })).status, 400);
  assert.equal((await post(`/api/publish-drafts/${id}/prepare`, { ...content, body: 'https://example.com' })).status, 400);
  assert.equal((await post(`/api/publish-drafts/${id}/prepare`, { ...content, title: '字'.repeat(21) })).status, 400);
  const response = await post(`/api/publish-drafts/${id}/prepare`, content);
  assert.equal(response.status, 201, await response.clone().text());
  const saved = await response.json();
  const pj = JSON.parse(fs.readFileSync(path.join(saved.dir, 'publish.json')));
  assert.equal(pj.mediaType, 'images'); assert.equal(pj.video, null);
  assert.deepEqual(pj.images, [second.file, first.file]); assert(!pj.schedule);
  assert.equal(getEpisode(saved.id).dir, saved.dir);
  assert.equal(getTasks(saved.id)[0].state, 'planned');
  assert.equal(JSON.parse(getSnapshot(saved.id).project).mediaType, 'images');
  assert.match(fs.readFileSync(path.join(saved.dir, '发布素材.md'), 'utf8'), /发布类型：图文/);
  assert.equal((await post(`/api/publish-drafts/${id}/prepare`, content)).status, 400);
  const episode = await (await fetch(`${base}/api/episode?id=${saved.id}`, { headers: auth })).json();
  assert.equal(episode.imageCount, 2); assert.equal(episode.mediaType, 'images');
  setTask(saved.id, 'xhs', 'awaiting_user');
  assert.equal((await post('/api/action', { type: 'fill-xhs', id: saved.id })).status, 409);
  assert.equal((await post('/api/action', { type: 'fill-xhs', id: 'missing' })).status, 400);
  assert.equal((await post('/api/action', { type: 'fill-xhs', id: saved.id }, { origin: 'https://other.example' })).status, 403);
  const video = await post('/api/publish-drafts', { mediaType: 'video' });
  const videoId = (await video.json()).id;
  assert.equal((await upload(videoId, 'not-video.png')).status, 400);
  assert.equal((await post(`/api/publish-drafts/${videoId}/prepare`, { ...content, assets: [] })).status, 400);
  const overviewResponse = await fetch(base + '/api/overview', { headers: auth });
  const overview = await overviewResponse.json();
  assert.equal(overviewResponse.status, 200, JSON.stringify(overview));
  assert.equal(overview.actions.length, 0);
  assert.equal(fs.existsSync(path.join(root, 'escape.png')), false);
});

test('markdown generator accepts image mode, uses numeric image order and rejects video-only targets', t => {
  // Uses a tiny local plugin fixture so these tests don't depend on an installed Chrome extension.
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mt-image-cli-'));
  t.after(() => fs.rmSync(tmp, { recursive: true, force: true }));
  const plugin = path.join(tmp, 'plugin'); fs.mkdirSync(path.join(plugin, 'lib'), { recursive: true });
  fs.writeFileSync(path.join(plugin, 'package.json'), '{"type":"module"}');
  fs.writeFileSync(path.join(plugin, 'lib', 'publish.js'), '');
  fs.writeFileSync(path.join(plugin, 'lib', 'bundle.js'), `export function validate(b){return {errors:b.video?[]:['缺少 video'],warnings:[]}};`);
  const cfg = path.join(tmp, 'config.json');
  fs.writeFileSync(cfg, JSON.stringify({ plugin: 'local', pluginDir: plugin }));
  const dir = path.join(tmp, 'image-project'); fs.mkdirSync(path.join(dir, '图片'), { recursive: true });
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aDVkAAAAASUVORK5CYII=', 'base64');
  for (const name of ['10.png', '2.png', '1.png']) fs.writeFileSync(path.join(dir, '图片', name), png);
  const md = path.join(dir, '发布素材.md');
  fs.writeFileSync(md, '# 测试\n\n> 发布类型：图文\n\n## 四、小红书\n**标题：**\n标题\n**正文：**\n正文\n#主题\n');
  const env = { ...process.env, MAITIAN_CONFIG: cfg };
  execFileSync(process.execPath, ['src/make-publish.mjs', md, dir], { env });
  let pj = JSON.parse(fs.readFileSync(path.join(dir, 'publish.json')));
  assert.equal(pj.mediaType, 'images'); assert.equal(pj.video, null);
  assert.deepEqual(pj.images, ['图片/1.png', '图片/2.png', '图片/10.png']);
  assert.equal(pj.platforms.xhs.body, '正文'); assert.deepEqual(pj.platforms.xhs.topics, ['主题']);
  fs.appendFileSync(md, '\n## 七、YouTube\n**标题：**\n标题\n');
  assert.throws(() => execFileSync(process.execPath, ['src/make-publish.mjs', md, dir], { env, stdio: 'pipe' }), e => e.status === 1 && /暂未接入图文/.test(e.stdout.toString()));
  pj = JSON.parse(fs.readFileSync(path.join(dir, 'publish.json')));
  assert.equal(pj.platforms.youtube.title, '标题');
});
